import mongoose from "mongoose";

const employeeRequestSchema = new mongoose.Schema(
  {
    fullName: {
      type: String,
      required: true,
      trim: true,
    },

    email: {
      type: String,
      required: true,
      unique: true,
      trim: true,
      lowercase: true,
    },

    phone: {
      type: String,
      required: true,
      trim: true,
    },

    status: {
      type: String,
      enum: ["pending", "approved", "rejected"],
      default: "pending",
    },
  },
  {
    timestamps: true,
  }
);

const EmployeeRequest =
  mongoose.models.EmployeeRequest ||
  mongoose.model("EmployeeRequest", employeeRequestSchema);

export default EmployeeRequest;